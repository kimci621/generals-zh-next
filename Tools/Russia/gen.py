def splice(path, body):
    s = open(path, encoding="utf-8").read()
    if BEGIN in s:
        a = s.index(BEGIN)
        b = s.index(END) + len(END)
        s = s[:a] + BEGIN + body + END + s[b:]
    else:
        s = s.rstrip("\n") + "\n\n" + BEGIN + body + END
    open(path, "w", encoding="utf-8").write(s)


def main():
    cb = open(os.path.join(sys.argv[1], "Data/INI/CommandButton.ini"), encoding="latin-1").read().replace("\r", "")

    def button(srcname, newname, obj):
        m = re.search(r"^CommandButton " + srcname + r"\n(.*?)^End", cb, re.S | re.M)
        assert m, srcname
        body = re.sub(r"(\n\s*Object\s*=\s*)\S+", r"\g<1>" + obj, "\n" + m.group(1))
        body = re.sub(r"(\n\s*TextLabel\s*=\s*)\S+", r"\g<1>CONTROLBAR:" + newname.replace("Command_", ""), body)
        return "CommandButton " + newname + body.rstrip("\n") + "\nEnd\n"

    sets = {"CommandCenter": "RussiaCommandCenterCommandSet", "VehicleIMR3M": "RussiaDozerCommandSet",
            "Barracks": "RussiaBarracksCommandSet", "SupplyCenter": "RussiaSupplyCenterCommandSet",
            "WarFactory": "RussiaWarFactoryCommandSet", "Airfield": "RussiaAirfieldCommandSet"}
    objs, btns, strs = [], [], []
    for i, src, c, t, req, en, ru, sb, *fac in BUILDINGS + UNITS:
        n, bn = "Russia" + i, "Command_ConstructRussia" + i
        o = f"ObjectReskin {n} {src}\nEnd\n\nObject {n}\n  Side = Russia\n"
        if i in sets:
            o += f"  CommandSet = {sets[i]}\n"
        o += f"  DisplayName = OBJECT:{n}\n  BuildCost = {c}\n  BuildTime = {t}.0\n"
        if req:
            o += f"  Prerequisites\n    Object = Russia{req}\n  End\n"
        objs.append(o + "End\n")
        if fac == [None]:
            continue
        btns.append(button(sb, bn, n))
        verb = ("&Build", "Построить") if not fac else ("&Train", "Подготовить")
        strs += [(f"OBJECT:{n}", en, ru), (f"CONTROLBAR:ConstructRussia{i}", f"{verb[0]} {en}", f"{verb[1]}: {ru}")]
    byfac = {}
    for i, *_, fac in UNITS:
        byfac.setdefault(fac, []).append(i)
    lines = ["CommandSet RussiaDozerCommandSet"] + [f"  {k} = Command_ConstructRussia{x}" for k, x in enumerate(DOZER, 1)]
    btns.append("\n".join(lines + ["  14 = Command_DisarmMinesAtPosition", "End"]) + "\n")
    cc = ["CommandSet RussiaCommandCenterCommandSet", "  1  = Command_ConstructRussiaVehicleIMR3M"]
    cc += [f"  {k} = {p}" for k, p in enumerate(CC_POWERS, 2)]
    btns.append("\n".join(cc + ["  13 = Command_SetRallyPoint", "  14 = Command_Sell", "End"]) + "\n")
    for fac in ("Barracks", "SupplyCenter", "WarFactory", "Airfield"):
        items = byfac.get(fac, [])
        assert len(items) <= 12, fac
        l = [f"CommandSet Russia{fac}CommandSet"] + [f"  {k} = Command_ConstructRussia{x}" for k, x in enumerate(items, 1)]
        btns.append("\n".join(l + ["  13 = Command_SetRallyPoint", "  14 = Command_Sell", "End"]) + "\n")
    splice(os.path.join(D, "INI/RussiaReforged.ini"), "\n".join(objs))
    splice(os.path.join(D, "INI/CommandSetReforged.ini"), "\n".join(btns))
    for p, idx in (("Patch.str", 1), ("Russian/Generals.str", 2)):
        path = os.path.join(D, p)
        s = open(path, encoding="utf-8").read()
        add = ""
        for st in strs:
            if f"\n{st[0]}\n" not in s:
                add += f'\n{st[0]}\n"' + st[idx].replace('"', '\\"') + '"\nEND\n'
        if add:
            open(path, "w", encoding="utf-8").write(s.rstrip("\n") + "\n" + add)


if __name__ == "__main__":
    main()
